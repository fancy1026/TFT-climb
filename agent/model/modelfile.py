"""The game model's principles: each a bullet "- [R<n> <status> <scope>] text" under a section's "What follows" (the
owner, 2026-10-26: the generalizable rules sit under the model). Status: active (the player reads it) or candidate
(waits for the replay test, agent/model/replay.py). Shared by build_memory.py (the player's playbook) and replay.py
(a model with a proposal applied)."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
MODEL = HERE / 'game-model.md'
BULLET = re.compile(r'^- \[R(\d+) (active|candidate) (general|patch)\] ', re.M)


def read():
    return MODEL.read_text(encoding='utf-8')


def _blocks(text):
    """[(start, end, id, status, scope)] of each principle bullet: its line and the indented lines that continue it."""
    out = []
    lines = text.splitlines(keepends=True)
    pos, i = 0, 0
    offsets = []
    for line in lines:
        offsets.append(pos)
        pos += len(line)
    while i < len(lines):
        m = BULLET.match(lines[i])
        if not m:
            i += 1
            continue
        j = i + 1
        while j < len(lines) and lines[j].startswith('  ') and lines[j].strip():
            j += 1
        out.append((offsets[i], offsets[j] if j < len(lines) else len(text), int(m.group(1)), m.group(2), m.group(3)))
        i = j
    return out


def principles(text=None):
    """[{id, status, scope, section, text}] in the model's order."""
    text = read() if text is None else text
    out = []
    for a, b, rid, status, scope in _blocks(text):
        sec = re.findall(r'^## (\d+)\. ([^\n]+)', text[:a], re.M)
        body = re.sub(r'\s+', ' ', BULLET.sub('', text[a:b])).strip()
        out.append({'id': f'R{rid}', 'status': status, 'scope': scope,
                    'section': f'{sec[-1][0]}. {sec[-1][1]}' if sec else '', 'text': body})
    return out


def active_text(text=None):
    """The model as the player reads it: candidate principles left out."""
    text = read() if text is None else text
    for a, b, _, status, _ in reversed(_blocks(text)):
        if status == 'candidate':
            text = text[:a] + text[b:]
    return text


def next_id(text=None):
    text = read() if text is None else text
    return 1 + max((int(r) for r in re.findall(r'\[R(\d+) ', text)), default=0)


def set_status(text, rid, status):
    """The model text with principle `rid` (e.g. 'R12') set to `status`."""
    n = int(str(rid).lstrip('R'))
    new, k = re.subn(rf'^- \[R{n} (active|candidate) ', f'- [R{n} {status} ', text, flags=re.M)
    if not k:
        raise KeyError(rid)
    return new


def apply_edits(text, edits):
    """Apply [{"old": exact text, "new": replacement}] in order; each old must occur exactly once."""
    for e in edits:
        if text.count(e['old']) != 1:
            raise ValueError(f"edit target occurs {text.count(e['old'])} times: {e['old'][:80]!r}")
        text = text.replace(e['old'], e['new'])
    return text


def remove(text, rid):
    """The model text without principle `rid`."""
    n = int(str(rid).lstrip('R'))
    for a, b, i, _, _ in _blocks(text):
        if i == n:
            return text[:a] + text[b:]
    raise KeyError(rid)


def playbook(text=None):
    """The player's playbook: the active model under its header."""
    model = active_text(text).strip()
    return ('# Playbook: the game model I decide with\n\n'
            'Generated by agent/model/build_memory.py from agent/model/game-model.md (active principles only). Each '
            'planning state also carries the CALCULATOR lines: the arithmetic of that moment (interest steps, when a '
            'level arrives and what it costs, where to roll for the units still needed, odds, what a loss costs, the HP '
            'runway).\n\n' + model.split('\n', 1)[1].strip() + '\n')
